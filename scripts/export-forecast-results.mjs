// Copies the forecast evaluation results (scenario A) into the app as a typed module.
// Numbers are read from scripts/synthetic/out/forecast-evaluation.json — never typed by hand.
// Run: npm run forecast:results
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('..', import.meta.url);
const input = fileURLToPath(new URL('scripts/synthetic/out/forecast-evaluation.json', root));
const output = fileURLToPath(new URL('src/data/forecastResults.ts', root));

const json = JSON.parse(await readFile(input, 'utf8'));
const a = json.scenarios?.A;
if (!a?.tasks?.infection || !a?.tasks?.fluid_loss) throw new Error('Scenario A results missing in forecast-evaluation.json');

const task = (t) => ({
  episodes: t.episodes,
  modelWarnedBeforePeak: t.modelWarnedBeforePeak,
  rulesAlertedBeforePeak: t.rulesAlertedBeforePeak,
  modelMedianDaysBeforePeak: t.modelMedianDaysBeforePeak,
});

const results = {
  source: 'scripts/synthetic/out/forecast-evaluation.json',
  scenario: 'A',
  scenarioTitle: a.title,
  label: json.label,
  testCrew: json.testCrew,
  infection: task(a.tasks.infection),
  fluidLoss: task(a.tasks.fluid_loss),
  normalDays: a.normalDays,
  normalDayWarnings: a.normalDayWarnings,
  normalDayWarningPct: a.normalDayWarningPct,
};

const body = `// GENERATED by scripts/export-forecast-results.mjs from ${results.source} — do not edit by hand.
// Run \`npm run forecast:results\` after re-running the forecast evaluation.

export const FORECAST_RESULTS = ${JSON.stringify(results, null, 2)} as const;
`;
await writeFile(output, body);
console.log(`Wrote ${output} (scenario A: infection ${results.infection.modelWarnedBeforePeak}/${results.infection.episodes}, fluid loss ${results.fluidLoss.modelWarnedBeforePeak}/${results.fluidLoss.episodes}, false warnings ${results.normalDayWarningPct}%)`);
