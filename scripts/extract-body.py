"""Extract the 2D body layers from Mikael Häggström's public-domain Wikimedia Commons diagram
"Man shadow anatomy - expanded.svg" (Human body diagrams project).

Usage: python -I scripts/extract-body.py
Reads  src/assets/body/Man_shadow_anatomy_-_expanded.svg
Writes src/assets/body/<organ>.png  (embedded organ bitmaps; the one GIF is converted to PNG)
       src/components/twin/bodyLayers.ts  (silhouette path + exact layer placement from the source)
"""
import base64
import json
import os
import re
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'src', 'assets', 'body', 'Man_shadow_anatomy_-_expanded.svg')
OUT_DIR = os.path.join(ROOT, 'src', 'assets', 'body')
TS = os.path.join(ROOT, 'src', 'components', 'twin', 'bodyLayers.ts')

# Source element id -> (organ group, file stem). Chosen and checked visually; all sized by the
# author to fit the same male silhouette.
LAYERS = [
    ('image7849', 'lungs', 'heart-and-lungs'),  # lungs (the heart part is covered by the heart layer)
    ('image10296', 'liver', 'liver'),
    ('image3706', 'stomach', 'stomach'),  # drawn over the liver's left lobe so both stay visible
    ('image3855', 'heart', 'heart'),
    ('image2204-9', 'brain', 'brain'),
    ('image3428', 'legs', 'thigh-muscles-right'),
    ('image3428-5', 'legs', 'thigh-muscles-left'),
    ('image3399', 'legs', 'lower-leg-muscles-right'),
    ('image3399-1', 'legs', 'lower-leg-muscles-left'),
]
SILHOUETTE_ID = 'path2180-7'
SILHOUETTE_PARENT_TRANSFORM = 'translate(202.73065,731.12631)'  # group layer1-1

s = open(SRC, encoding='utf-8').read()


def element(tag, el_id):
    for m in re.finditer(r'<' + tag + r'\b(.*?)/>', s, re.S):
        if re.search(r'\sid="' + re.escape(el_id) + r'"', m.group(1)):
            return m.group(1)
    raise SystemExit(f'{el_id} not found')


def attr(a, k):
    m = re.search(r'\s' + re.escape(k) + r'="([^"]*)"', a)
    return m.group(1) if m else None


layers = []
for el_id, organ, stem in LAYERS:
    a = element('image', el_id)
    href = attr(a, 'xlink:href')
    mime = re.match(r'data:image/(\w+);base64,', href).group(1)
    ext = {'jpeg': 'jpg'}.get(mime, mime)
    name = f'{stem}.{ext}'
    with open(os.path.join(OUT_DIR, name), 'wb') as f:
        f.write(base64.b64decode(href.split(',', 1)[1]))
    if ext == 'gif':  # GIF -> PNG (keeps transparency; GIF is not decoded by every SVG renderer)
        png = f'{stem}.png'
        subprocess.run(['node', '-e', "require('sharp')(process.argv[1]).png().toFile(process.argv[2]).then(()=>0)",
                        os.path.join(OUT_DIR, name), os.path.join(OUT_DIR, png)], check=True, cwd=ROOT)
        os.remove(os.path.join(OUT_DIR, name))
        name = png
    layers.append({
        'organ': organ,
        'file': name,
        'source': el_id,
        'x': float(attr(a, 'x')),
        'y': float(attr(a, 'y')),
        'width': float(attr(a, 'width')),
        'height': float(attr(a, 'height')),
        'transform': attr(a, 'transform'),
    })
    print(f'{el_id:12s} -> {name:30s} ({organ})')

sil = element('path', SILHOUETTE_ID)
d = re.sub(r'\s+', ' ', attr(sil, 'd')).strip()

imports = '\n'.join(f"import {re.sub(r'[^a-zA-Z]', '', l['file'].split('.')[0].title())} from '../../assets/body/{l['file']}';" for l in layers)
items = ',\n'.join(
    '  { organ: %s, href: %s, x: %s, y: %s, width: %s, height: %s, transform: %s, source: %s }' % (
        json.dumps(l['organ']), re.sub(r'[^a-zA-Z]', '', l['file'].split('.')[0].title()), l['x'], l['y'], l['width'], l['height'],
        json.dumps(l['transform']) if l['transform'] else 'undefined', json.dumps(l['source']))
    for l in layers)
ts = f"""// GENERATED by scripts/extract-body.py from Wikimedia Commons "Man shadow anatomy - expanded.svg"
// (Mikael Häggström, public domain). Coordinates are the source document's user units.
{imports}

export type BodyOrgan = 'brain' | 'lungs' | 'heart' | 'liver' | 'stomach' | 'legs';

export interface BodyLayer {{
  organ: BodyOrgan;
  href: string;
  x: number;
  y: number;
  width: number;
  height: number;
  transform?: string;
  source: string;
}}

/** Organ bitmaps in drawing order (back to front). */
export const BODY_LAYERS: BodyLayer[] = [
{items},
];

/** Male silhouette (front view, arms down). */
export const SILHOUETTE = {{
  d: {json.dumps(d)},
  transform: {json.dumps(SILHOUETTE_PARENT_TRANSFORM)},
}};
"""
open(TS, 'w', encoding='utf-8').write(ts)
print('wrote', os.path.relpath(TS, ROOT), f'(silhouette path {len(d)} chars)')
